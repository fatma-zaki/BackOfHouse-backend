/**
 * Storage port (ADR-009, nest-module-map.md §3). The media module (Stage 5)
 * builds the quarantine → scan → move flow on top of it. Clients only ever
 * receive short-lived signed URLs; bucket names and paths are chosen here.
 */
export interface SignedUpload {
  path: string;
  signedUrl: string;
  token: string;
}

export interface StoragePort {
  createSignedUploadUrl(bucket: string, path: string): Promise<SignedUpload>;
  createSignedDownloadUrl(bucket: string, path: string, ttlSeconds: number): Promise<string>;
  move(fromBucket: string, fromPath: string, toBucket: string, toPath: string): Promise<void>;
  remove(bucket: string, paths: string[]): Promise<void>;
}

export const STORAGE_PORT = Symbol('STORAGE_PORT');

/** Object paths are generated by the server: segments of safe characters only. */
const SAFE_PATH = /^[A-Za-z0-9_-]+(\/[A-Za-z0-9_-]+)*(\.[a-z0-9]{1,8})?$/;

export function assertSafeObjectPath(path: string): void {
  if (path.length > 512 || !SAFE_PATH.test(path)) {
    throw new Error('Unsafe storage object path');
  }
}
